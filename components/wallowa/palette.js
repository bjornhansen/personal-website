export function createPalette() {
  const p = {}
  COLOR_KEYS.forEach((c) => (p[c] = new THREE.Color()))
  NUMBER_KEYS.forEach((n) => (p[n] = 0))
  return p
}

export function samplePalette(altitude, out) {
  let i = 0
  while (i < KEYFRAMES.length - 2 && altitude > KEYFRAMES[i + 1].altitude) i++
  const a = KEYFRAMES[i]
  const b = KEYFRAMES[i + 1]
  const t = THREE.MathUtils.smoothstep(altitude, a.altitude, b.altitude)
  COLOR_KEYS.forEach((c) => out[c].copy(a[c]).lerp(b[c], t))
  NUMBER_KEYS.forEach((n) => (out[n] = THREE.MathUtils.lerp(a[n], b[n], t)))
  return out
}
